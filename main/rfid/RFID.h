/**
 * @file RFID.h
 * @brief Публичный интерфейс RFID-подсистемы.
 *
 * @details
 * Заголовочный файл объявляет структуру для хранения UID RFID-карты
 * и функцию инициализации считывателя RC522.
 */


#ifndef RFID_INCL
#define RFID_INCL

#include<stdint.h>


/**
 * @brief Представляет UID RFID-карты.
 *
 * @details
 * UID хранится как последовательность байтов. Поле `size` содержит
 * фактическую длину UID, а `bytes` — сами байты идентификатора.
 * Максимальная длина, поддерживаемая этой структурой, составляет 10 байт.
 *
 * Структура используется при передаче UID из RFID-подсистемы
 * в сетевую подсистему для отправки на сервер.
 */
typedef struct {
     /** Фактическое количество байтов в UID. */
    uint8_t size;

    /** Массив байтов UID; максимальная вместимость — 10 байт. */
    uint8_t bytes[10];
} RFIDCard;


/**
 * @brief Инициализирует RFID-считыватель RC522.
 *
 * @details
 * Функция настраивает SPI-подключение к RC522, создаёт и устанавливает
 * драйвер, создаёт экземпляр считывателя, регистрирует обработчик события
 * изменения состояния PICC и запускает считыватель.
 *
 * После запуска обнаружение карты обрабатывается асинхронно зарегистрированным
 * обработчиком событий. При обнаружении поддерживаемой карты её UID
 * передаётся сетевой функции `sendRequest()`.
 *
 * @note Параметры SPI и GPIO задаются в реализации RFID.c через макросы
 *       конфигурации RC522.
 *
 * @warning Текущая реализация не возвращает код ошибки: результаты вызовов
 *          создания и запуска драйвера не проверяются вызывающим кодом.
 *
 * @return Нет.
 */
void RFIDinit();

#endif /* RFID_INCL */