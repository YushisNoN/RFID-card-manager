/**
 * @file gui.h
 * @brief Публичный интерфейс графического интерфейса RFID-терминала.
 *
 * @details
 * Модуль предоставляет функции инициализации TFT-дисплея и управления
 * отображаемыми состояниями RFID-терминала. Для построения интерфейса
 * используется LVGL, а для связи с дисплеем — драйвер ESP-IDF esp_lcd.
 *
 * Все публичные функции изменения интерфейса безопасно обращаются к LVGL
 * через блокировку lvgl_port.
 *
 * @note Перед вызовом gui_show_*() необходимо успешно выполнить gui_init().
 */


#ifndef GUI_H
#define GUI_H

#include "esp_lcd_panel_ops.h"
#include "esp_err.h"

#include <stdint.h>

/**
 * @brief Состояния графического интерфейса RFID-терминала.
 *
 * @details
 * Значение перечисления определяет содержимое центральной области дисплея,
 * цветовую схему индикации и запускаемые анимации.
 */
typedef enum {
    /** Ожидание карты: отображается приглашение приложить карту. */
    GUI_STATE_WAITING,

    /** Проверка карты: отображается процесс обращения к серверу. */
    GUI_STATE_READING,

    /** Успешная обработка карты: показывается зелёная индикация. */
    GUI_STATE_SUCCESS,

    /** Ошибка обработки карты: показывается красная индикация. */
    GUI_STATE_ERROR
} GUI_State;

/**
 * @brief Инициализирует TFT-дисплей и графическую библиотеку LVGL.
 *
 * @details
 * Функция инициализирует SPI-шину дисплея, создаёт интерфейс esp_lcd,
 * сбрасывает и запускает контроллер ST7789, включает дисплей, запускает
 * порт LVGL, регистрирует дисплей в LVGL и создаёт элементы интерфейса.
 * После создания интерфейса устанавливается состояние GUI_STATE_WAITING.
 *
 * @return Дескриптор панели дисплея esp_lcd_panel_handle_t при успешной
 *         инициализации; NULL при ошибке.
 *
 * @note Функцию следует вызвать до gui_show_waiting(), gui_show_reading(),
 *       gui_show_success() и gui_show_error().
 * @warning Функция настраивает GPIO и SPI-шину в соответствии с параметрами,
 *          определёнными в gui.c.
 */
esp_lcd_panel_handle_t gui_init(void);

/**
 * @brief Переводит интерфейс в состояние ожидания RFID-карты.
 *
 * @details Отображает приглашение приложить карту и запускает анимацию
 *          бесконтактного сигнала.
 */
void gui_show_waiting(void);

/**
 * @brief Показывает, что RFID-карта проверяется.
 *
 * @details Отображает сообщение о проверке и запускает анимацию индикатора
 *          процесса обработки.
 */
void gui_show_reading(void);

/**
 * @brief Показывает успешную обработку RFID-карты.
 *
 * @details Отображает зелёную индикацию и обратный отсчёт. Через пять секунд
 *          интерфейс автоматически возвращается в GUI_STATE_WAITING.
 */
void gui_show_success(void);

/**
 * @brief Показывает ошибку обработки RFID-карты.
 *
 * @details Отображает красную индикацию и обратный отсчёт. Через три секунды
 *          интерфейс автоматически возвращается в GUI_STATE_WAITING.
 */
void gui_show_error(void);

#endif /* GUI_H */