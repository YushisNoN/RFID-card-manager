#ifndef WEB_INCL
#define WEB_INCL

/**
 * @file web.h
 * @brief Публичный интерфейс сетевого модуля RFID Manager.
 *
 * @details
 * Модуль отвечает за подключение ESP32 к Wi-Fi и обмен данными
 * с сервером RFID Manager по HTTP. Также он предоставляет функцию
 * запуска точки доступа и веб-страницы для первоначальной настройки
 * параметров беспроводной сети.
 */
#include "RFID.h"

#include <stdio.h>
#include <string.h>

#include "esp_http_client.h"
#include "esp_log.h"

#include "esp_wifi.h"
#include "esp_event.h"
#include "esp_netif.h"
#include "freertos/event_groups.h"

/**
 * @brief Отправляет UID RFID-карты на сервер для проверки.
 *
 * @details
 * Формирует JSON-объект с размером UID и массивом его байтов,
 * после чего отправляет его POST-запросом на HTTP endpoint сервера.
 * Перед отправкой функция ожидает появления признака подключения
 * станции ESP32 к Wi-Fi, но не более пяти секунд.
 *
 * В текущей реализации успешным считается только HTTP-ответ со
 * статусом 200. Любой другой HTTP-статус трактуется как отказ.
 *
 * @param[in] uid Структура RFIDCard с длиной UID и байтами идентификатора.
 *
 * @retval ESP_OK Запрос выполнен, сервер вернул HTTP 200.
 * @retval ESP_ERR_INVALID_ARG Передан UID нулевой длины или длиной больше
 *         размера массива uid.bytes.
 * @retval ESP_ERR_TIMEOUT ESP32 не подключилась к Wi-Fi за пять секунд.
 * @retval ESP_ERR_INVALID_SIZE Не удалось сформировать JSON в выделенном буфере.
 * @retval ESP_FAIL Не удалось создать HTTP-клиент или получить ожидаемые данные.
 * @retval Другой esp_err_t Код ошибки HTTP-клиента.
 *
 * @note Функция не разбирает JSON-тело ответа сервера: решение принимается
 *       только по HTTP-статусу.
 */
esp_err_t sendRequest(RFIDCard uid);

/**
 * @brief Инициализирует Wi-Fi в режимах точки доступа и станции.
 *
 * @details
 * Загружает сохранённые параметры сети из NVS, настраивает SoftAP
 * для доступа к странице конфигурации и при наличии сохранённых
 * параметров запускает подключение к внешней Wi-Fi сети.
 * Также регистрирует обработчики Wi-Fi/IP-событий и запускает
 * встроенный HTTP-сервер настройки.
 *
 * @note Функция не ожидает успешного подключения станции к роутеру.
 *       Состояние подключения отслеживается через обработчик событий,
 *       а sendRequest() отдельно ожидает признак WIFI_CONNECTED_BIT.
 *
 * @warning Перед публикацией прошивки следует заменить стандартный
 *          пароль точки доступа на собственный и не хранить реальные
 *          пароли внешних сетей в исходном коде.
 */
void wifi_init_sta(void);


#endif