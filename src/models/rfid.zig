//! # RFID
//!
//! Данный модуль содержит структуры данных,
//! используемые для представления информации,
//! полученной от RFID-карт.
//!
//! Отвечает за:
//! - Определение формата данных RFID-карты.
//! - Хранение UID карты, полученного от контроллера.
//! - Представление данных, передаваемых в HTTP-запросах.

const std = @import("std");

/// Структура запроса, содержащего данные RFID-карты.
///
/// Используется для представления информации о карте,
/// полученной от ESP32 через HTTP API.
///
/// Содержит размер UID и массив байтов, составляющих UID.
///
/// Поля:
///     size: Количество байтов в UID карты.
///     bytes: Массив байтов, содержащий UID карты.
///
/// Ограничения:
///     Значение `size` должно соответствовать количеству
///     элементов массива `bytes`.
///
/// Memory:
///     Массив `bytes` не копируется при создании структуры.
///     Структура хранит срез, поэтому время жизни исходного
///     массива должно быть не меньше времени использования среза.
pub const RFIDCardRequest = struct {
    /// Количество байтов в UID RFID-карты.
    size: usize,

    /// Массив байтов, представляющий UID RFID-карты.
    bytes: []const u8,
};
